"""Localized texts for the ekcos article "ëkcos vs. other suppliers".

Extracted verbatim from the 22 comparison-guide PDFs (no machine translation).
LOCALES maps locale code -> {"meta": {...}, "texts": {...}}; every locale has
the identical set of texts keys (see _build).
"""

from __future__ import annotations

FEATURE_COUNT = 13


def _build(
    *,
    intro: str,
    glance: str,
    bio: str,
    days: str,
    grams: str,
    bristles: str,
    proof: str,
    test: tuple[str, str],
    patents: tuple[str, str],
    ppwr: tuple[str, str],
    sds: tuple[str, str],
    compare: str,
    ask: str,
    features: list[tuple[str, str, str]],
    advantages: str,
    material: tuple[str, list[str]],
    performance: tuple[str, list[str]],
    fragrance: tuple[str, list[str]],
    design: tuple[str, list[str]],
    cubicle: tuple[str, list[str]],
    marketing: tuple[str, list[str]],
    cta: tuple[str, str, str, str],
) -> dict[str, str]:
    assert len(features) == FEATURE_COUNT
    t: dict[str, str] = {
        "intro": intro,
        "h2-glance": glance,
        "stat-bio": bio,
        "stat-days": days,
        "stat-grams": grams,
        "stat-bristles": bristles,
        "h2-proof": proof,
        "proof-test-title": test[0],
        "proof-test-body": test[1],
        "proof-patents-title": patents[0],
        "proof-patents-body": patents[1],
        "proof-ppwr-title": ppwr[0],
        "proof-ppwr-body": ppwr[1],
        "proof-sds-title": sds[0],
        "proof-sds-body": sds[1],
        "h2-compare": compare,
        "ask-label": ask,
    }
    for i, (name, ekcos, ask_q) in enumerate(features, start=1):
        t[f"f{i}-name"] = name
        t[f"f{i}-ekcos"] = ekcos
        t[f"f{i}-ask"] = ask_q
    t["h2-advantages"] = advantages
    groups = {
        "material": (material, 3),
        "performance": (performance, 4),
        "fragrance": (fragrance, 2),
        "design": (design, 2),
        "cubicle": (cubicle, 3),
        "marketing": (marketing, 4),
    }
    for key, ((h3, bullets), n) in groups.items():
        assert len(bullets) == n, key
        t[f"adv-{key}-h3"] = h3
        for j, b in enumerate(bullets, start=1):
            t[f"adv-{key}-{j}"] = b
    t["h2-cta"] = cta[0]
    t["cta-1"] = cta[1]
    t["cta-2"] = cta[2]
    t["cta-3"] = cta[3]
    return t


